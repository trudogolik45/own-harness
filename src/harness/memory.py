"""Память проекта: AGENTS.md / CLAUDE.md подмешиваются в системный промпт каждой сессии."""
from __future__ import annotations

from pathlib import Path

MEMORY_FILES = ("AGENTS.md", "CLAUDE.md")

BASE_PROMPT = """Ты — ассистент-разработчик. С файлами и командами работай только через инструменты.
Вызывай инструменты по очереди, пока задача не сделана, и только потом отвечай пользователю.

Как чинить баг:
1. Сначала запусти тесты проекта (обычно `uv run pytest -q`) и прочитай, какой тест падает и почему.
2. Прочитай падающий тест (read_file), найди проверяемый код через search.
3. Исправь минимально через edit_file: меняй только то, что ломает тест.
4. Снова запусти тесты. Повторяй, пока не будут зелёными. После трёх неудачных попыток остановись и объясни, что мешает.

Честность:
- Шаг сделан, только если инструмент вернул успех, а не error: у команды exit code 0, у edit_file ответ edited, у write_file — written.
- Не утверждай, что тесты зелёные, файл изменён или коммит сделан, если не видел этого в выводе инструмента.
- Если команду отклонили или она упала, так и скажи пользователю.
"""


def build_system_prompt(root: Path) -> str:
    workdir = f"Рабочая директория: {root.resolve()}. Пути в инструментах пиши относительно неё, например src/app.py."
    sections = [BASE_PROMPT, workdir]
    for name in MEMORY_FILES:
        file = root / name
        if file.is_file():
            sections.append(f"## {name}\n{file.read_text().strip()}")
    return "\n\n".join(sections)
